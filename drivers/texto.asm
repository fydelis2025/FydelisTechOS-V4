texto_iniciar:
    cmp     qword [fb_base], 0
    je      .erro
    cmp     dword [fb_largura], 0
    je      .erro
    cmp     dword [fb_altura], 0
    je      .erro
    xor     rax, rax
    ret
.erro:
    mov     rax, -1
    ret

texto_limpar_tela:
    cmp     qword [fb_base], 0
    je      .fim
    mov     rdi, [fb_base]
    mov     eax, COR_FUNDO
    mov     ecx, [fb_largura]
    imul    ecx, [fb_altura]
    rep     stosd
.fim:
    ret

; ENTRADA: ESI = X, EDI = Y, R8B = char ASCII, ECX = cor
texto_char:
    cmp     qword [fb_base], 0
    je      .ret_rapido

    push    rbp
    mov     rbp, rsp
    push    rbx
    push    rsi
    push    rdi
    push    r9
    push    r10
    push    r11
    push    r12

    mov     r9d, ecx
    and     r8b, 0x7F
    movzx   rax, r8b
    shl     rax, 3
    mov     rbx, fonte_8x8
    add     rbx, rax

    mov     r10d, [fb_pitch]
    test    r10d, r10d
    jnz     .pitch_ok
    mov     r10d, [fb_largura]
    shl     r10d, 2
.pitch_ok:

    mov     eax, edi
    imul    rax, r10
    mov     r11, [fb_base]
    add     r11, rax
    mov     eax, esi
    shl     rax, 2
    add     r11, rax

    mov     r12b, 8
.linha:
    mov     al, [rbx]
    mov     rdx, r11
    mov     r8b, 8
.coluna:
    test    al, 0x80
    jz      .pular
    mov     [rdx], r9d
.pular:
    shl     al, 1
    add     rdx, 4
    dec     r8b
    jnz     .coluna

    add     r11, r10
    inc     rbx
    dec     r12b
    jnz     .linha

    pop     r12
    pop     r11
    pop     r10
    pop     r9
    pop     rdi
    pop     rsi
    pop     rbx
    pop     rbp
.ret_rapido:
    ret

; ENTRADA: ESI = X, EDI = Y, RDX = string, ECX = cor
texto_string:
    push    rbp
    mov     rbp, rsp
    push    rbx
    push    rsi
    push    rdi
    push    r12
    push    r13

    mov     r12, rdx
    mov     r13d, esi
    mov     ebx, esi
    mov     r9d, ecx

.proximo:
    movzx   eax, byte [r12]
    test    al, al
    jz      .fim

    cmp     al, 10
    je      .quebra_linha
    cmp     al, 13
    je      .ignora

    mov     esi, ebx
    mov     r8b, al
    mov     ecx, r9d
    call    texto_char

    add     ebx, 9
    inc     r12
    jmp     .proximo

.quebra_linha:
    mov     ebx, r13d
    add     edi, 12
.ignora:
    inc     r12
    jmp     .proximo

.fim:
    pop     r13
    pop     r12
    pop     rdi
    pop     rsi
    pop     rbx
    pop     rbp
    ret

; ENTRADA: EDI = Y, RDX = string, ECX = cor
texto_centralizado:
    push    rbp
    mov     rbp, rsp
    push    rsi
    push    rdi
    push    rbx
    push    r12

    mov     r12, rdx
    xor     rcx, rcx
.contar:
    cmp     byte [r12 + rcx], 0
    je      .contado
    inc     rcx
    jmp     .contar
.contado:
    mov     rax, rcx
    imul    rax, 9
    mov     ecx, [fb_largura]
    sub     rcx, rax
    shr     rcx, 1
    mov     esi, ecx

    mov     rdx, r12
    mov     ecx, [texto_cor]
    call    texto_string

    pop     r12
    pop     rbx
    pop     rdi
    pop     rsi
    pop     rbp
    ret

